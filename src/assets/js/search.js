/* ==========================================================================
   GolfSimCanada.site — Client-Side Search (Phase 15/17)
   SSOT Reference: 13-build-flow.md §17.4
   Logic: Fetches generated search-index.json and provides instant results.
   ========================================================================== */

document.addEventListener('DOMContentLoaded', () => {
  const searchInput = document.getElementById('search-input');
  const searchResults = document.getElementById('search-results');
  
  if (!searchInput || !searchResults) return;

  let searchIndex = [];
  let isLoaded = false;

  // Fetch the search index generated by build.js
  async function fetchSearchIndex() {
    try {
      const response = await fetch('/assets/js/search-index.json');
      if (response.ok) {
        searchIndex = await response.json();
        isLoaded = true;
      }
    } catch (error) {
      console.error('Failed to load search index:', error);
    }
  }

  // Debounce helper
  function debounce(func, wait) {
    let timeout;
    return function executedFunction(...args) {
      const later = () => {
        clearTimeout(timeout);
        func(...args);
      };
      clearTimeout(timeout);
      timeout = setTimeout(later, wait);
    };
  }

  function displayResults(query) {
    if (!query) {
      searchResults.innerHTML = '';
      searchResults.style.display = 'none';
      return;
    }

    const q = query.toLowerCase();
    
    // Filter index based on title, description, or keywords
    const matches = searchIndex.filter(item => {
      const matchTitle = (item.title || '').toLowerCase().includes(q);
      const matchDesc = (item.description || '').toLowerCase().includes(q);
      const matchKeywords = (item.keywords || []).some(k => k.toLowerCase().includes(q));
      return matchTitle || matchDesc || matchKeywords;
    }).slice(0, 8); // limit to top 8 results

    if (matches.length > 0) {
      searchResults.innerHTML = matches.map(item => `
        <a href="${item.url}" class="search-result-item" style="display: block; padding: 12px; border-bottom: 1px solid var(--color-border); text-decoration: none;">
          <h4 style="margin: 0; color: #fff; font-size: 16px;">${item.title}</h4>
          <p style="margin: 4px 0 0 0; color: var(--color-text-secondary); font-size: 14px;">${item.description}</p>
        </a>
      `).join('');
      
      // View all link
      searchResults.innerHTML += `
        <div style="padding: 12px; text-align: center; background: var(--color-bg-overlay);">
          <span style="color: var(--color-text-secondary); font-size: 14px;">Showing top results</span>
        </div>
      `;
    } else {
      searchResults.innerHTML = `<div style="padding: 16px; color: var(--color-text-secondary);">No results found for "${query}"</div>`;
    }

    searchResults.style.display = 'block';
  }

  const handleInput = debounce((e) => {
    const query = e.target.value.trim();
    displayResults(query);
  }, 250);

  searchInput.addEventListener('focus', () => {
    if (!isLoaded) fetchSearchIndex();
    const query = searchInput.value.trim();
    if (query) displayResults(query);
  });

  searchInput.addEventListener('input', handleInput);

  // Close results when clicking outside
  document.addEventListener('click', (e) => {
    if (!searchInput.contains(e.target) && !searchResults.contains(e.target)) {
      searchResults.style.display = 'none';
    }
  });
});
